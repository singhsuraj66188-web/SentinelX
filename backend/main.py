# MONITORING CYCLE
# ============================================================

def monitoring_cycle():

    print(
        "\n========== MONITORING CYCLE =========="
    )

    # --------------------------------------------
    # START MONITORING CYCLE
    # --------------------------------------------

    log_event(
        "SYSTEM",
        "Monitoring cycle started",
        "INFO"
    )

    # --------------------------------------------
    # SYSTEM STATUS
    # --------------------------------------------

    display_system_status()

    system_snapshot = collect_system_snapshot()

    # --------------------------------------------
    # PROCESS MONITORING
    # --------------------------------------------

    print(
        "Collecting running processes..."
    )

    raw_processes = get_running_processes()
    process_list = get_process_list()

    print(
        "Analyzing processes..."
    )

    # --------------------------------------------
    # BASIC PROCESS DETECTION
    # --------------------------------------------

    alerts = analyze_processes(
        raw_processes
    )

    # --------------------------------------------
    # PROCESS METADATA ANALYSIS
    # --------------------------------------------

    metadata_processes = {
        "powershell.exe",
        "wscript.exe",
        "cscript.exe",
        "mshta.exe",
        "regsvr32.exe",
        "rundll32.exe"
    }

    for process in process_list:

        process_name = normalize_process_name(
            process.get(
                "name",
                ""
            )
        )

        if process_name in metadata_processes:

            try:

                metadata = get_process_details(
                    process["pid"]
                )

                metadata_alerts = (
                    analyze_process_metadata(
                        metadata
                    )
                )

                alerts.extend(
                    metadata_alerts
                )

            except Exception as error:

                pid = process.get(
                    "pid",
                    "Unknown"
                )

                print(
                    f"Metadata analysis failed for "
                    f"{process_name} "
                    f"(PID {pid}): "
                    f"{error}"
                )

                log_event(
                    "SYSTEM",
                    (
                        f"Metadata analysis failed for "
                        f"{process_name} "
                        f"(PID {pid})"
                    ),
                    "INFO"
                )

    # --------------------------------------------
    # DUPLICATE ALERT CORRELATION
    # --------------------------------------------

    original_alert_count = len(
        alerts
    )

    alerts = deduplicate_alerts(
        alerts
    )

    deduplicated_alert_count = len(
        alerts
    )

    removed_alert_count = (
        original_alert_count
        - deduplicated_alert_count
    )

    if removed_alert_count > 0:

        print(
            f"Alert correlation removed "
            f"{removed_alert_count} "
            f"duplicate detection(s)."
        )

        log_event(
            "SYSTEM",
            (
                f"Alert correlation removed "
                f"{removed_alert_count} "
                f"duplicate detection(s)"
            ),
            "INFO"
        )

    # ========================================================
    # IMPORTANT:
    #
    # Keep ALL currently active alerts separately.
    #
    # These are used for CURRENT RISK.
    #
    # Only NEW alerts are used for SECURITY_ALERT events.
    # ========================================================

    active_alerts = list(
        alerts
    )

    # --------------------------------------------
    # NEW PROCESS EXECUTION FILTER
    # --------------------------------------------

    previous_alert_count = len(
        alerts
    )

    new_alerts = filter_new_process_alerts(
        alerts,
        process_list
    )

    suppressed_alert_count = (
        previous_alert_count
        - len(new_alerts)
    )

    if suppressed_alert_count > 0:

        print(
            f"Process-state tracking suppressed "
            f"{suppressed_alert_count} "
            f"already-active alert(s)."
        )

        log_event(
            "SYSTEM",
            (
                f"Process-state tracking suppressed "
                f"{suppressed_alert_count} "
                f"already-active alert(s)"
            ),
            "INFO"
        )

    # --------------------------------------------
    # SECURITY ANALYSIS DISPLAY
    # --------------------------------------------

    if new_alerts:

        display_alerts(
            new_alerts
        )

    else:

        print(
            "No new suspicious process executions detected."
        )

    # --------------------------------------------
    # SAVE NEW SECURITY ALERTS ONLY
    # --------------------------------------------

    for alert in new_alerts:

        message = (
            f"{alert['process']} - "
            f"{alert['reason']}"
        )

        pid = alert.get(
            "pid"
        )

        if pid is not None:

            message = (
                f"{message} "
                f"(PID: {pid})"
            )

        log_event(
            "SECURITY_ALERT",
            message,
            alert["severity"]
        )

        alert_risk_score = calculate_risk_score(
            [alert]
        )

        save_and_sync_event(
            event_type="SECURITY_ALERT",
            message=message,
            severity=alert["severity"],
            process=alert["process"],
            risk_score=alert_risk_score
        )

    # ========================================================
    # CURRENT RISK ASSESSMENT
    #
    # IMPORTANT:
    #
    # Risk is calculated from ALL currently active
    # suspicious processes, not only newly generated alerts.
    #
    # Therefore:
    #
    # New rundll32.exe:
    #     SECURITY_ALERT + Risk 20
    #
    # Same rundll32.exe next cycle:
    #     No SECURITY_ALERT + Risk 20
    #
    # rundll32.exe disappears:
    #     No active alert + Risk 0
    # ========================================================

    risk_score = calculate_risk_score(
        active_alerts
    )

    display_risk_score(
        risk_score
    )

    log_event(
        "RISK_ASSESSMENT",
        f"Risk score: {risk_score}/100",
        "INFO"
    )

    save_and_sync_event(
        event_type="RISK_ASSESSMENT",
        message=f"Risk score: {risk_score}/100",
        severity="INFO",
        risk_score=risk_score
    )

    # --------------------------------------------
    # NETWORK MONITORING
    # --------------------------------------------

    print(
        "Collecting network connections..."
    )

    connections = get_network_connections()

    connection_count = len(
        [
            line
            for line in connections.splitlines()
            if line.strip()
        ]
    )

    print(
        f"Network records collected: "
        f"{connection_count}"
    )

    log_event(
        "NETWORK",
        (
            f"{connection_count} "
            f"network records collected"
        ),
        "INFO"
    )

    save_and_sync_event(
        event_type="NETWORK",
        message=(
            f"{connection_count} "
            f"network records collected"
        ),
        severity="INFO",
        risk_score=risk_score
    )

    # --------------------------------------------
    # WINDOWS SNAPSHOT
    # --------------------------------------------

    print(
        "Preparing Windows monitoring snapshot..."
    )

    try:

        snapshot_result = send_monitoring_snapshot(
            system_snapshot=system_snapshot,
            processes=process_list,
            network_connections=connections,
            risk_score=risk_score
        )

        if snapshot_result:

            print(
                "Windows snapshot synchronization: SUCCESS"
            )

        else:

            print(
                "Windows snapshot synchronization: FAILED"
            )

    except Exception as error:

        print(
            f"Windows snapshot synchronization "
            f"error: {error}"
        )

    # --------------------------------------------
    # CYCLE COMPLETE
    # --------------------------------------------

    log_event(
        "SYSTEM",
        "Monitoring cycle completed",
        "INFO"
    )

    print(
        "======================================="
    )


