# ============================================================
# ALERT SEVERITY PRIORITY
# ============================================================

SEVERITY_PRIORITY = {
    "INFO": 0,
    "LOW": 20,
    "MEDIUM": 50,
    "HIGH": 75,
    "CRITICAL": 100
}


# ============================================================
# ALERT DEDUPLICATION
# ============================================================

def deduplicate_alerts(alerts):
    """
    Remove duplicate alerts generated by different
    detection layers during the same monitoring cycle.

    If the same process is detected multiple times,
    the alert with the highest severity is retained.

    Example:

        Basic detector:
        rundll32.exe -> LOW

        Metadata detector:
        rundll32.exe -> HIGH

    Final result:

        rundll32.exe -> HIGH

    This prevents one real detection from being counted
    as multiple security alerts.
    """

    if not alerts:
        return []

    unique_alerts = {}

    for alert in alerts:

        process = str(
            alert.get("process", "")
        ).lower().strip()

        reason = str(
            alert.get("reason", "")
        ).strip()

        severity = str(
            alert.get("severity", "INFO")
        ).upper().strip()

        # ----------------------------------------------------
        # Use process as the primary correlation key.
        #
        # SentinelX treats multiple detections of the same
        # monitored process as one security alert per cycle.
        # ----------------------------------------------------

        alert_key = process

        # If process name is unavailable, use reason so that
        # the alert is still handled safely.
        if not alert_key:
            alert_key = reason.lower()

        # ----------------------------------------------------
        # First occurrence
        # ----------------------------------------------------

        if alert_key not in unique_alerts:

            unique_alerts[alert_key] = {
                "process": alert.get(
                    "process",
                    "Unknown"
                ),
                "reason": reason,
                "severity": severity
            }

            continue

        # ----------------------------------------------------
        # Duplicate occurrence
        #
        # Keep the more serious detection.
        # ----------------------------------------------------

        existing_alert = unique_alerts[alert_key]

        existing_severity = str(
            existing_alert.get(
                "severity",
                "INFO"
            )
        ).upper()

        existing_score = SEVERITY_PRIORITY.get(
            existing_severity,
            0
        )

        new_score = SEVERITY_PRIORITY.get(
            severity,
            0
        )

        if new_score > existing_score:

            unique_alerts[alert_key] = {
                "process": alert.get(
                    "process",
                    "Unknown"
                ),
                "reason": reason,
                "severity": severity
            }

        elif new_score == existing_score:

            # If both have the same severity, prefer the
            # more specific detection reason when possible.
            if reason and reason != existing_alert.get(
                "reason",
                ""
            ):

                existing_reason = existing_alert.get(
                    "reason",
                    ""
                )

                if len(reason) > len(existing_reason):

                    unique_alerts[alert_key] = {
                        "process": alert.get(
                            "process",
                            "Unknown"
                        ),
                        "reason": reason,
                        "severity": severity
                    }

    return list(
        unique_alerts.values()
    )


# ============================================================
# CLOUD EVENT SENDER
# ============================================================

def send_event_to_cloud(
    event_type,
    message,
    severity="INFO",
    process=None,
    risk_score=0,
    timestamp=None
):
    """
    Send a SentinelX event to the Render cloud API.

    Local storage remains independent from cloud storage.
    If cloud ingestion fails, SentinelX continues running.
    """

    if not CLOUD_INGEST_KEY:

        print(
            "Cloud ingestion skipped: "
            "INGEST_API_KEY is not configured."
        )

        return False

    if timestamp is None:

        timestamp = datetime.now().strftime(
            "%Y-%m-%d %H:%M:%S"
        )

    event_data = {
        "timestamp": timestamp,
        "event_type": event_type,
        "severity": severity,
        "process": process or "",
        "message": message,
        "risk_score": int(risk_score)
    }

    try:

        request_data = json.dumps(
            event_data
        ).encode("utf-8")

        request = Request(
            CLOUD_INGEST_URL,
            data=request_data,
            headers={
                "Content-Type": "application/json",
                "X-SentinelX-Key": CLOUD_INGEST_KEY
            },
            method="POST"
        )

        with urlopen(
            request,
            timeout=15
        ) as response:

            response.read()

            if response.status in (200, 201):

                print(
                    "Cloud event uploaded successfully."
                )

                return True

            print(
                f"Cloud ingestion returned HTTP "
                f"{response.status}"
            )

            return False

    except HTTPError as error:

        print(
            f"Cloud ingestion HTTP error: "
            f"{error.code} {error.reason}"
        )

        return False

    except URLError as error:

        print(
            f"Cloud ingestion connection error: "
            f"{error.reason}"
        )

        return False

    except Exception as error:

        print(
            f"Cloud ingestion error: {error}"
        )

        return False


