# ============================================================
# ALERT SEVERITY PRIORITY
# ============================================================

SEVERITY_PRIORITY = {
    "INFO": 0,
    "LOW": 20,
    "MEDIUM": 50,
    "HIGH": 75,
    "CRITICAL": 100
}


# ============================================================
# PROCESS STATE TRACKING
# ============================================================

# Stores suspicious process identities that were already
# observed during previous monitoring cycles.
#
# Primary identity:
#
#     process_name + PID
#
# If PID information is unavailable, SentinelX falls back
# to process name.
#
# This prevents the same continuously-running process from
# generating a new SECURITY_ALERT every 30 seconds.

PREVIOUS_SUSPICIOUS_PROCESSES = set()


# ============================================================
# ALERT DEDUPLICATION
# ============================================================

def deduplicate_alerts(alerts):
    """
    Remove duplicate alerts generated by different
    detection layers during the same monitoring cycle.

    If the same process is detected multiple times,
    the alert with the highest severity is retained.
    """

    if not alerts:
        return []

    unique_alerts = {}

    for alert in alerts:

        process = str(
            alert.get("process", "")
        ).lower().strip()

        reason = str(
            alert.get("reason", "")
        ).strip()

        severity = str(
            alert.get("severity", "INFO")
        ).upper().strip()

        alert_key = process

        if not alert_key:
            alert_key = reason.lower()

        if alert_key not in unique_alerts:

            unique_alerts[alert_key] = {
                "process": alert.get(
                    "process",
                    "Unknown"
                ),
                "reason": reason,
                "severity": severity
            }

            continue

        existing_alert = unique_alerts[alert_key]

        existing_severity = str(
            existing_alert.get(
                "severity",
                "INFO"
            )
        ).upper()

        existing_score = SEVERITY_PRIORITY.get(
            existing_severity,
            0
        )

        new_score = SEVERITY_PRIORITY.get(
            severity,
            0
        )

        if new_score > existing_score:

            unique_alerts[alert_key] = {
                "process": alert.get(
                    "process",
                    "Unknown"
                ),
                "reason": reason,
                "severity": severity
            }

        elif new_score == existing_score:

            existing_reason = existing_alert.get(
                "reason",
                ""
            )

            if (
                reason
                and reason != existing_reason
                and len(reason) > len(existing_reason)
            ):

                unique_alerts[alert_key] = {
                    "process": alert.get(
                        "process",
                        "Unknown"
                    ),
                    "reason": reason,
                    "severity": severity
                }

    return list(
        unique_alerts.values()
    )


