# CLOUD EVENT SENDER
# ============================================================

def send_event_to_cloud(
    event_type,
    message,
    severity="INFO",
    process=None,
    risk_score=0,
    timestamp=None
):
    """
    Send a SentinelX event to the Render cloud API.

    Local storage remains independent from cloud storage.
    If cloud ingestion fails, SentinelX continues running.
    """

    if not CLOUD_INGEST_KEY:

        print(
            "Cloud ingestion skipped: "
            "INGEST_API_KEY is not configured."
        )

        return False

    if timestamp is None:

        timestamp = datetime.now().strftime(
            "%Y-%m-%d %H:%M:%S"
        )

    event_data = {
        "timestamp": timestamp,
        "event_type": event_type,
        "severity": severity,
        "process": process or "",
        "message": message,
        "risk_score": int(risk_score)
    }

    try:

        request_data = json.dumps(
            event_data
        ).encode("utf-8")

        request = Request(
            CLOUD_INGEST_URL,
            data=request_data,
            headers={
                "Content-Type": "application/json",
                "X-SentinelX-Key": CLOUD_INGEST_KEY
            },
            method="POST"
        )

        with urlopen(
            request,
            timeout=15
        ) as response:

            response.read()

            if response.status in (200, 201):

                print(
                    "Cloud event uploaded successfully."
                )

                return True

            print(
                f"Cloud ingestion returned HTTP "
                f"{response.status}"
            )

            return False

    except HTTPError as error:

        print(
            f"Cloud ingestion HTTP error: "
            f"{error.code} {error.reason}"
        )

        return False

    except URLError as error:

        print(
            f"Cloud ingestion connection error: "
            f"{error.reason}"
        )

        return False

    except Exception as error:

        print(
            f"Cloud ingestion error: {error}"
        )

        return False


