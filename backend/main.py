def collect_system_snapshot():
    """
    Collect system information from the Windows machine
    running SentinelX.
    """

    try:

        hostname = socket.gethostname()

    except Exception:

        hostname = "Unknown"

    # --------------------------------------------------------
    # SentinelX dashboard display name
    #
    # This does NOT change the actual Windows account.
    # --------------------------------------------------------

    try:

        username = "Suraj Baliarsingh"

    except Exception:

        username = os.environ.get(
            "USERNAME",
            "Unknown"
        )

    try:

        operating_system = platform.system()

    except Exception:

        operating_system = "Unknown"

    try:

        os_version = platform.version()

    except Exception:

        os_version = "Unknown"

    return {
        "hostname": hostname,
        "operating_system": operating_system,
        "os_version": os_version,
        "username": username
    }


# ============================================================
# CLOUD SNAPSHOT SENDER
# ============================================================

def send_monitoring_snapshot(
    system_snapshot,
    processes,
    network_connections,
    risk_score
):
    """
    Upload the latest Windows monitoring snapshot.

    Snapshot contains:

        - Windows system information
        - running processes
        - network connections
        - current risk score
        - timestamp
    """

    if not CLOUD_INGEST_KEY:

        print(
            "Cloud snapshot skipped: "
            "INGEST_API_KEY is not configured."
        )

        return False

    timestamp = datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S"
    )

    snapshot_data = {
        "timestamp": timestamp,
        "system": system_snapshot,
        "processes": processes,
        "network": network_connections,
        "risk_score": int(risk_score)
    }

    try:

        request_data = json.dumps(
            snapshot_data
        ).encode("utf-8")

        request = Request(
            CLOUD_SNAPSHOT_URL,
            data=request_data,
            headers={
                "Content-Type": "application/json",
                "X-SentinelX-Key": CLOUD_INGEST_KEY
            },
            method="POST"
        )

        with urlopen(
            request,
            timeout=20
        ) as response:

            response.read()

            if response.status in (200, 201):

                print(
                    "Windows monitoring snapshot "
                    "uploaded successfully."
                )

                return True

            print(
                f"Cloud snapshot returned HTTP "
                f"{response.status}"
            )

            return False

    except HTTPError as error:

        print(
            f"Cloud snapshot HTTP error: "
            f"{error.code} {error.reason}"
        )

        return False

    except URLError as error:

        print(
            f"Cloud snapshot connection error: "
            f"{error.reason}"
        )

        return False

    except Exception as error:

        print(
            f"Cloud snapshot error: {error}"
        )

        return False


# ============================================================
# SAVE LOCAL + CLOUD EVENT
# ============================================================

def save_and_sync_event(
    event_type,
    message,
    severity="INFO",
    process=None,
    risk_score=0
):
    """
    Save an event locally and then attempt cloud ingestion.

    Local storage is never dependent on cloud availability.
    """

    timestamp = datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S"
    )

    # --------------------------------------------------------
    # LOCAL STORAGE
    # --------------------------------------------------------

    local_saved = save_event(
        event_type=event_type,
        message=message,
        severity=severity,
        process=process,
        risk_score=risk_score,
        timestamp=timestamp
    )

    # --------------------------------------------------------
    # CLOUD STORAGE
    # --------------------------------------------------------

    cloud_saved = send_event_to_cloud(
        event_type=event_type,
        message=message,
        severity=severity,
        process=process,
        risk_score=risk_score,
        timestamp=timestamp
    )

    return local_saved, cloud_saved


