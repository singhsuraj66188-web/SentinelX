def main():

    print(
        "Starting SentinelX...\n"
    )

    show_banner()

    # --------------------------------------------
    # DATABASE INITIALIZATION
    # --------------------------------------------

    initialize_database()

    # --------------------------------------------
    # CLOUD STATUS
    # --------------------------------------------

    if CLOUD_INGEST_KEY:

        print(
            "Cloud ingestion: ENABLED"
        )

        print(
            f"Cloud API: {CLOUD_INGEST_URL}"
        )

        print(
            f"Snapshot API: {CLOUD_SNAPSHOT_URL}"
        )

    else:

        print(
            "Cloud ingestion: DISABLED"
        )

        print(
            "Set INGEST_API_KEY to enable "
            "cloud upload."
        )

    # --------------------------------------------
    # START LOGGING
    # --------------------------------------------

    log_event(
        "SYSTEM",
        "SentinelX continuous monitoring started",
        "INFO"
    )

    # --------------------------------------------
    # CONTINUOUS MONITORING
    # --------------------------------------------

    try:

        while True:

            monitoring_cycle()

            print(
                "\nNext monitoring cycle in "
                "30 seconds..."
            )

            print(
                "Press Ctrl+C to stop SentinelX."
            )

            time.sleep(30)

    except KeyboardInterrupt:

        print(
            "\nSentinelX stopped by user."
        )

        log_event(
            "SYSTEM",
            "SentinelX stopped by user",
            "INFO"
        )

        save_and_sync_event(
            event_type="SYSTEM",
            message="SentinelX stopped by user",
            severity="INFO",
            risk_score=0
        )


# ============================================================
# PROGRAM ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()